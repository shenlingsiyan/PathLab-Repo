#Requires -Version 5.1
<#
    Copies every algorithm folder from /algorithms into the carrier's
    /PathLab/Algorithms directory. The carrier compiles those copies.

    Source of truth:  algorithms/<NN_name>/*.cs + README.md
    Generated copy:   PathLab/Algorithms/<NN_name>/
#>
$ErrorActionPreference = 'Stop'

$root = Split-Path -Parent $PSScriptRoot
$source = Join-Path $root 'algorithms'
$destination = Join-Path $root 'PathLab\Algorithms'

if (-not (Test-Path -LiteralPath $source)) {
    throw "algorithm source folder not found: $source"
}

if (Test-Path -LiteralPath $destination) {
    Remove-Item -LiteralPath $destination -Recurse -Force
}
New-Item -ItemType Directory -Path $destination | Out-Null

$synced = 0
foreach ($folder in Get-ChildItem -LiteralPath $source -Directory | Sort-Object Name) {
    $files = Get-ChildItem -LiteralPath $folder.FullName -Filter *.cs -File
    if ($files.Count -eq 0) {
        Write-Warning "skip $($folder.Name): no .cs file"
        continue
    }

    $target = Join-Path $destination $folder.Name
    New-Item -ItemType Directory -Path $target | Out-Null

    foreach ($file in $files) {
        Copy-Item -LiteralPath $file.FullName -Destination $target
    }

    $readme = Join-Path $folder.FullName 'README.md'
    if (Test-Path -LiteralPath $readme) {
        Copy-Item -LiteralPath $readme -Destination $target
    }

    Write-Host "copied $($folder.Name) -> $target"
    $synced++
}

$note = @(
    'Generated by tools/sync-algorithms.ps1. Do not edit files in this folder.'
    'Edit the matching folder under /algorithms, then rerun the script.'
) -join [Environment]::NewLine

Set-Content -LiteralPath (Join-Path $destination '_COPIED.txt') -Value $note -Encoding UTF8

Write-Host "synced $synced algorithm module(s) to $destination"
